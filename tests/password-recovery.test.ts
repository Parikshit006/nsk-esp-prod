import {afterAll,beforeAll,it,expect} from 'vitest';
import request from 'supertest';
import {Pool} from 'pg';
import {createApp} from '../apps/api/src/app.js';
import {readConfig} from '../apps/api/src/config.js';
import {migrate} from '../apps/api/src/migrations.js';
const url=process.env.DATABASE_URL_TEST;if(!url||!new URL(url).pathname.endsWith('_test'))throw new Error('A separate _test database is required.');
const schema=`test_${crypto.randomUUID().replaceAll('-','')}`,admin=new Pool({connectionString:url}),pool=new Pool({connectionString:url,options:`-c search_path=${schema}`});
const sent:{email:string;link:string}[]=[];
const app=createApp(readConfig({NODE_ENV:'test',DATABASE_URL:url,WEB_ORIGIN:'http://localhost:5173',READINESS_TOKEN:'recovery-test-token-with-more-than-32-characters'}),pool,()=>{},async(email,link)=>{sent.push({email,link});});
beforeAll(async()=>{await admin.query(`CREATE SCHEMA ${schema}`);await migrate(pool);});
afterAll(async()=>{await pool.end();await admin.query(`DROP SCHEMA ${schema} CASCADE`);await admin.end();});
it('issues one-use recovery links without revealing accounts and revokes sessions',async()=>{
  const agent=request.agent(app),email='recover@example.test',oldPassword='old-password-1234',newPassword='new-password-1234';
  expect((await agent.post('/api/v1/auth/register').send({email,password:oldPassword,display_name:'Recovery Captain'})).status).toBe(201);
  expect((await agent.post('/api/v1/auth/login').send({email,password:oldPassword})).status).toBe(200);
  const unknown=await agent.post('/api/v1/auth/request-password-reset').send({email:'absent@example.test'});
  const first=await agent.post('/api/v1/auth/request-password-reset').send({email});
  expect(first.status).toBe(202);expect(first.body).toEqual(unknown.body);expect(sent).toHaveLength(1);
  const firstToken=sent[0]!.link.split('#')[1]!;
  await agent.post('/api/v1/auth/request-password-reset').send({email});
  const secondToken=sent[1]!.link.split('#')[1]!;
  expect((await agent.post('/api/v1/auth/reset-password').send({token:firstToken,new_password:newPassword})).status).toBe(400);
  expect((await agent.post('/api/v1/auth/reset-password').send({token:secondToken,new_password:newPassword})).status).toBe(200);
  expect((await agent.post('/api/v1/auth/reset-password').send({token:secondToken,new_password:newPassword})).status).toBe(400);
  expect((await agent.get('/api/v1/auth/me')).status).toBe(401);
  expect((await agent.post('/api/v1/auth/login').send({email,password:oldPassword})).status).toBe(401);
  expect((await agent.post('/api/v1/auth/login').send({email,password:newPassword})).status).toBe(200);
  const audit=await pool.query("SELECT after_value FROM audit_events WHERE action='account.password_reset'");expect(audit.rowCount).toBe(1);expect(JSON.stringify(audit.rows)).not.toContain(newPassword);
  const tokens=await pool.query('SELECT token_hash FROM password_reset_tokens');expect(JSON.stringify(tokens.rows)).not.toContain(secondToken);
});
